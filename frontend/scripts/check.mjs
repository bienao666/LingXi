import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = name => readFileSync(path.join(root, name), 'utf8');
new vm.Script(read('assets/boot/boot.js'));
const context = { exports: {} };
vm.runInNewContext(ts.transpile(read('src/navigation.ts'), { module: ts.ModuleKind.CommonJS }), context);
const { groups, modules, store, routes } = context.exports;
assert.equal(modules.length, 10, '一级菜单应为 10 项');
assert.equal(routes.length, 47, '41 个主应用页面与 6 个商店占位页面');
assert.equal(new Set(routes.map(route => route.href)).size, routes.length, '路由须唯一');
for (const item of [...groups, ...modules, ...store, ...routes]) assert.equal(Array.from(item.label).length, 4, `四字命名：${item.label}`);
const html = read('index.html');
for (const match of html.matchAll(/(?:src|href)="(\/[^"#]+)"/g)) assert.ok(existsSync(path.join(root, match[1].slice(1))), `本地资源缺失：${match[1]}`);
const preset = JSON.parse(read('assets/boot/preset.json'));
const exported = JSON.parse(read('assets/boot/boot.js').match(/\/\* PRESET_START \*\/([\s\S]*?)\/\* PRESET_END \*\//)[1]);
assert.deepEqual(exported, preset, '动画 JSON 与浏览器导出需同步');
assert.equal(preset.stages.length, 10);
assert.equal(preset.defaults.brand.name, '灵犀');
const allCss = read('assets/theme/theme.css') + read('assets/boot/boot.css') + read('styles/boot-theme.css') + read('styles/app.css') + read('styles/business.css') + read('styles/startup.css');
const declarations = new Set([...allCss.matchAll(/(--[\w-]+)\s*:/g)].map(match => match[1]));
for (const match of (read('styles/app.css') + read('styles/boot-theme.css') + read('styles/business.css') + read('styles/startup.css')).matchAll(/var\((--[\w-]+)/g)) assert.ok(declarations.has(match[1]), `缺失 Token：${match[1]}`);
assert.ok(!/#(?:[\da-f]{3}){1,2}\b/i.test(read('styles/app.css')), '应用样式应使用主题 Token');
assert.ok(!/https?:\/\//.test(html), '入口不依赖外部资源');
console.log('检查通过：JavaScript 语法、10 个四字一级菜单、47 个唯一路由、本地资源、10 阶段动画同步与 CSS Token 引用。');
